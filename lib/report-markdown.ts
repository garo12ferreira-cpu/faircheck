// Turns a report into Markdown, e.g. to paste into a pull-request description.

import type { ScanReport, Severity } from "./scanner/types";

const ICON: Record<Severity, string> = { high: "🔴", medium: "🟠", low: "🔵", info: "⚪" };

export function reportToMarkdown(r: ScanReport): string {
  const out: string[] = [];
  out.push(`## FairCheck bias review: ${r.title}`);
  out.push("");
  out.push(`**Risk:** ${r.risk} · 🔴 ${r.counts.high} high · 🟠 ${r.counts.medium} medium · 🔵 ${r.counts.low} low`);
  out.push("");
  out.push(r.summary);
  out.push("");
  const issues = r.findings.filter((f) => f.severity !== "info");
  if (issues.length === 0) out.push("_No issues found._");
  for (const f of issues) {
    const where = f.line ? ` (line ${f.line})` : "";
    out.push(`### ${ICON[f.severity]} ${f.title}${where}`);
    out.push(`_${f.category}${f.source === "ai" ? " · AI review" : ""}_`);
    if (f.snippet) out.push("", "```", f.snippet, "```");
    out.push("", f.explanation, "", `**Fix:** ${f.suggestion}`, "");
  }
  const dismissed = r.findings.filter((f) => f.aiNote);
  if (dismissed.length) {
    out.push("<details><summary>Rule hits the AI judged harmless</summary>", "");
    for (const f of dismissed) out.push(`- ${f.title}${f.line ? ` (line ${f.line})` : ""}: ${f.aiNote}`);
    out.push("", "</details>");
  }
  out.push("", `<sub>Generated by FairCheck on ${new Date(r.createdAt).toLocaleString("en-GB")}</sub>`);
  return out.join("\n");
}
